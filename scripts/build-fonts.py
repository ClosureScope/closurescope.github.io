"""Subset Chinese webfonts from rendered HTML; never modify the local PDF fonts."""
import hashlib
import json
import sys
from html.parser import HTMLParser
from pathlib import Path

from fontTools import subset, version
from fontTools.ttLib import TTFont

ROOT = Path(__file__).resolve().parent.parent
SOURCES = ROOT / "site/public/fonts"
OUTPUT = SOURCES / "subsets"


class VisibleText(HTMLParser):
    def __init__(self):
        super().__init__(convert_charrefs=True)
        self.hidden = 0
        self.parts = []

    def handle_starttag(self, tag, attrs):
        if tag in ("style", "script"):
            self.hidden += 1

    def handle_endtag(self, tag):
        if tag in ("style", "script"):
            self.hidden -= 1

    def handle_data(self, data):
        if not self.hidden:
            self.parts.append(data)


posts = json.load(sys.stdin)
parser = VisibleText()
for post in posts:
    parser.feed(post["body"])
    parser.parts.extend([post["title"], post["category"]])
# Include navigation, index headings, and dates as well as article text.
for file in sorted((ROOT / "site/src").rglob("*.astro")):
    parser.parts.append(file.read_text())
parser.parts.append((ROOT / "scripts/categories.mjs").read_text())
codepoints = sorted(set(map(ord, "".join(parser.parts))) | set(range(32, 127)))
OUTPUT.mkdir(parents=True, exist_ok=True)
faces = []
for filename, family, weight, styles in [
    ("NotoSerifSC-variable.woff2", "Noto Serif SC", "200 900", ["normal"]),
    ("NotoSansSC-variable.woff2", "Noto Sans SC", "100 900", ["normal"]),
    # Map the upright Kai face to italic CSS: only Latin should be italicized.
    ("FandolKai-Regular.woff2", "FandolKai", "400", ["normal", "italic"]),
]:
    source = SOURCES / filename
    digest = hashlib.sha256(source.read_bytes() + json.dumps(codepoints).encode()
                            + version.encode() + b"all-layout-features-v2").hexdigest()[:16]
    destination = OUTPUT / f"{source.stem}-{digest}.woff2"
    if not destination.exists():
        font = TTFont(source, recalcTimestamp=False)
        options = subset.Options()
        options.layout_features = ["*"]
        options.notdef_glyph = True
        options.notdef_outline = True
        subsetter = subset.Subsetter(options=options)
        subsetter.populate(unicodes=codepoints)
        subsetter.subset(font)
        font.flavor = "woff2"
        temporary = destination.with_suffix(".tmp")
        font.save(temporary)
        temporary.replace(destination)
    for style in styles:
        faces.append(f'@font-face {{ font-family: "{family}"; '
                     f'src: url("/fonts/subsets/{destination.name}") format("woff2"); '
                     f'font-weight: {weight}; font-style: {style}; font-display: swap; }}')

css = "/* Generated by scripts/build-fonts.py; retains variable weight axes. */\n" + "\n".join(faces) + "\n"
target = ROOT / ".generated/fonts.css"
if not target.exists() or target.read_text() != css:
    target.write_text(css)
# Keep earlier hashes during dev so pages already open can finish loading fonts.
print(f"[fonts] 中文字体已按 {len(codepoints)} 个字符生成并缓存。")
